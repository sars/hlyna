// What the chat says before the visitor writes, by kind of page. Static text (no model call until someone writes).
export type ChatKind = 'profile' | 'business' | 'classes' | 'home' | 'other'

export type ChatOpener = { kicker: string; title: string; intro: string; chips: string[] }

export function chatOpener(kind: ChatKind, o: { studioName?: string; city?: string; classes?: boolean; business?: boolean } = {}): ChatOpener {
  const city = o.city ? ` у ${o.city}` : ''
  switch (kind) {
    case 'profile': {
      const chips = [
        ...(o.classes ? ['Хочу записатися на майстер-клас', 'Скільки коштує заняття для двох?'] : []),
        ...(o.business ? ['Потрібна партія посуду для закладу', 'Скільки коштують 50 чашок з логотипом?'] : []),
        ...(!o.classes && !o.business ? ['Хочу замовити виріб', 'Де подивитися роботи?'] : []),
      ].slice(0, 3)
      return {
        kicker: 'Чат · безкоштовно',
        title: o.studioName ? `Питайте про «${o.studioName}»` : 'Питайте про студію',
        intro: 'Я помічник Глини: відповім одразу з даних профілю про запис, виріб чи партію. Людина з Глини підключиться, коли треба.',
        chips,
      }
    }
    case 'business':
      return {
        kicker: 'Чат · для бізнесу',
        title: 'Що потрібно і до якої дати?',
        intro: 'Я помічник Глини: скажу орієнтовні ціни й терміни, назву студії, які таке роблять, і передам один запит кільком із них.',
        chips: ['Скільки коштують 50 чашок з логотипом?', 'Які терміни на партію посуду?', 'Шукаю корпоратив з глиною для команди'],
      }
    case 'classes':
      return {
        kicker: 'Чат · майстер-класи',
        title: `Куди піти на гончарство${city}?`,
        intro: 'Я помічник Глини. Скажіть, скільки вас, коли і який формат: коло, ліплення чи розпис, і я підкажу 2–3 студії з цінами.',
        chips: ['Скільки коштує заняття для двох?', 'Шукаю майстер-клас для дитини', 'Де є подарунковий сертифікат?'],
      }
    case 'home':
      return {
        kicker: 'Чат · безкоштовно',
        title: 'Що шукаєте?',
        intro: 'Я помічник Глини: майстер-клас у вашому місті, подарунок з кераміки чи посуд для закладу. Відповідаю одразу, людина підключиться, коли треба.',
        chips: ['Шукаю майстер-клас у своєму місті', 'Потрібен подарунок з кераміки', 'Потрібен посуд для ресторану'],
      }
    default:
      return {
        kicker: 'Чат · безкоштовно',
        title: 'Напишіть, що потрібно',
        intro: 'Я помічник Глини: відповідаю одразу з даних каталогу, людина з Глини підключається, коли треба.',
        chips: ['Шукаю студію у своєму місті', 'Скільки коштує майстер-клас?', 'Хочу замовити партію посуду'],
      }
  }
}
