// Copy editorial city/product content from the research folder into the repo and validate it.
//   node scripts/sync-place-content.mjs            (SRC=/path/to/_site_content to override)
// Writes src/content/places/{cities,products}/<slug>.json and src/content/places/index.ts (static imports,
// so the content ships inside the build). Format: UkraineCeramics/_site_content/BRIEF.md.
// Slugs linked in the text are checked against public_studios.json when it is there; pages also check
// them at render time against published studios, so an unknown slug shows as plain text, never a broken link.
import fs from 'node:fs'
import path from 'node:path'

const SRC = process.env.SRC || '/Users/rodik/Claude/UkraineCeramics/_site_content'
const OUT = path.resolve('src/content/places')
const KINDS = ['cities', 'products']

const published = (() => {
  try {
    return new Set(JSON.parse(fs.readFileSync(path.join(SRC, 'public_studios.json'), 'utf8')).map((s) => s.slug))
  } catch {
    return null
  }
})()

const str = (v) => typeof v === 'string' && v.trim().length > 0
const LINK = /\[([^\]]+)\]\(([^)\s]+)\)/g
let problems = 0
const warn = (f, msg) => {
  problems++
  console.warn(`${f}: ${msg}`)
}

const index = {}
for (const kind of KINDS) {
  const dir = path.join(SRC, kind)
  fs.mkdirSync(path.join(OUT, kind), { recursive: true })
  index[kind] = []
  if (!fs.existsSync(dir)) continue
  for (const file of fs.readdirSync(dir).filter((f) => f.endsWith('.json')).sort()) {
    const f = `${kind}/${file}`
    let d
    try {
      d = JSON.parse(fs.readFileSync(path.join(dir, file), 'utf8'))
    } catch (e) {
      warn(f, `invalid JSON (${e.message}), skipped`)
      continue
    }
    const slug = file.replace(/\.json$/, '')
    if (d.slug !== slug) warn(f, `slug "${d.slug}" ≠ file name, using "${slug}"`)
    const out = {
      slug,
      lead: str(d.lead) ? d.lead.trim() : '',
      scene: (Array.isArray(d.scene) ? d.scene : []).filter(str).map((s) => s.trim()),
      picks: (Array.isArray(d.picks) ? d.picks : [])
        .filter((p) => p && str(p.need) && Array.isArray(p.slugs) && p.slugs.length)
        .map((p) => ({ need: p.need.trim(), slugs: p.slugs.filter(str), why: str(p.why) ? p.why.trim() : '' })),
      faq: (Array.isArray(d.faq) ? d.faq : []).filter((x) => x && str(x.q) && str(x.a)).map((x) => ({ q: x.q.trim(), a: x.a.trim() })),
      seeAlso: (Array.isArray(d.seeAlso) ? d.seeAlso : []).filter(str).map((s) => s.trim()),
      // Internal research file paths are not shown on the site: only public URLs.
      sources: [...new Set((Array.isArray(d.sources) ? d.sources : []).filter((s) => str(s) && /^https?:\/\//.test(s)))],
    }
    if (!out.lead) warn(f, 'no lead')
    if (published) {
      const linked = [...out.scene.join(' ').matchAll(LINK)].map((m) => m[2]).filter((s) => !s.startsWith('/'))
      for (const s of [...linked, ...out.picks.flatMap((p) => p.slugs)]) if (!published.has(s)) warn(f, `unknown studio slug "${s}" (renders as plain text)`)
    }
    fs.writeFileSync(path.join(OUT, kind, `${slug}.json`), JSON.stringify(out, null, 1) + '\n')
    index[kind].push(slug)
  }
}

const id = (kind, slug) => `${kind}_${slug.replace(/[^a-z0-9]/g, '_')}`
const lines = [
  '// Generated by scripts/sync-place-content.mjs — do not edit by hand.',
  "import type { PlaceContent } from '@/lib/places'",
  '',
  ...KINDS.flatMap((kind) => index[kind].map((slug) => `import ${id(kind, slug)} from './${kind}/${slug}.json'`)),
  '',
  ...KINDS.map((kind) => `export const ${kind}: Record<string, PlaceContent> = {\n${index[kind].map((slug) => `  '${slug}': ${id(kind, slug)},`).join('\n')}\n}`),
  '',
]
fs.writeFileSync(path.join(OUT, 'index.ts'), lines.join('\n'))
console.log(`cities ${index.cities.length}, products ${index.products.length}, warnings ${problems}`)
